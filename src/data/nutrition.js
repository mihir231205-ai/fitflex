export function searchFoods(query) {
  const q = query.trim().toLowerCase()
  if (!q) return FOODS
  return FOODS.filter(
    (food) =>
      food.name.toLowerCase().includes(q) ||
      food.aliases.some((alias) => alias.includes(q)),
  )
}
